    static std::string getEntityName(u8 kind, u8 id) {
        for (const auto& ent : getEntityRegistry()) {
            if (ent.kind == kind && ent.id == id) {
                return ent.name;
            }
        }
        char buf[64];
        std::snprintf(buf, sizeof(buf), "Unknown Kind %u ID 0x%02X", kind, id);
        return buf;
    }

    static std::string getItemName(u8 id) {
        for (const auto& item : getItemRegistry()) {
            if (item.id == id) {
                return item.name;
            }
        }
        char buf[64];
        std::snprintf(buf, sizeof(buf), "Item 0x%02X", id);
        return buf;
    }

    static std::string getAreaName(u8 id) {
        for (const auto& area : getAreas()) {
            if (area.id == id) {
                return area.name;
            }
        }
        char buf[64];
        std::snprintf(buf, sizeof(buf), "Area %u", id);
        return buf;
    }
